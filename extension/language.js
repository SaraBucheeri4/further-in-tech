const alertLanguageKey = "alertLanguage";
function resolveAlertLanguage(preference) {
  if (preference === "en" || preference === "ar") return preference;
  return /^ar(?:-|$)/i.test(chrome.i18n.getUILanguage()) ? "ar" : "en";
}
